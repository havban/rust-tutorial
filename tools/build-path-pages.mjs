#!/usr/bin/env node
/**
 * Generates a standalone landing page per learning path:
 *
 *   fast-track.html   full-course.html   assets/og/<permalink>.png
 *
 * Why these exist at all: the app is hash-routed, so `/#/fast-track` is a fine
 * in-app route but a poor thing to *share* — crawlers and link-preview bots
 * (Slack, WhatsApp, Twitter, Google) never see the fragment, so every shared
 * link would show the site's generic title and description. These pages are
 * real URLs with their own metadata, and they hand off into the app.
 *
 * They are generated from the lesson data so the lesson list cannot drift.
 *
 *   node tools/build-path-pages.mjs            # HTML only
 *   node tools/build-path-pages.mjs --og       # HTML + regenerate OG images
 */

import { mkdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PATHS, pathMinutes } from "../assets/js/lessons/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://havban.github.io/rust-tutorial";
const WITH_OG = process.argv.includes("--og");

const esc = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/** Strip the Markdown a summary may contain — meta tags must be plain text. */
const plain = (s) =>
  String(s)
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1");

function pageHtml(path) {
  const lessons = path.modules.flatMap((m) => m.lessons);
  const minutes = pathMinutes(path);
  const url = `${SITE}/${path.permalink}.html`;
  const description = plain(
    `${path.blurb} ${lessons.length} lessons${minutes ? `, about ${minutes} minutes` : ""}. Every one has an editable program you compile and run in the browser against a real Rust toolchain.`,
  );

  const modules = path.modules
    .map((mod) => {
      const modMinutes = mod.lessons.reduce((t, l) => t + (l.minutes || 0), 0);
      const items = mod.lessons
        .map(
          (l) => `          <li>
            <a href="index.html#/${esc(l.slug)}">${esc(l.title)}</a>${
              l.minutes ? `<span class="min">${l.minutes}m</span>` : ""
            }
            <span class="sum">${esc(plain(l.summary || ""))}</span>
          </li>`,
        )
        .join("\n");
      return `        <section class="mod">
          <div class="mod-head">
            <span class="mod-n">${String(mod.n).padStart(2, "0")}</span>
            <h2>${esc(mod.title)}</h2>${
              modMinutes ? `\n            <span class="mod-min">${modMinutes} min</span>` : ""
            }
          </div>
          <p class="mod-sum">${esc(plain(mod.summary))}</p>
          <ol class="lessons">
${items}
          </ol>
        </section>`;
    })
    .join("\n");

  const other = PATHS.find((p) => p.id !== path.id);

  return `<!doctype html>
<!-- GENERATED by tools/build-path-pages.mjs — edit the lesson data, not this file. -->
<html lang="en" data-theme="dark">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(path.title)} — ${esc(path.tagline)} · Rust Tutorial</title>
    <meta name="description" content="${esc(description)}" />
    <link rel="canonical" href="${url}" />
    <meta name="color-scheme" content="dark light" />

    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Rust Tutorial" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${esc(path.title)} — ${esc(path.tagline)}" />
    <meta property="og:description" content="${esc(description)}" />
    <meta property="og:image" content="${SITE}/assets/og/${esc(path.permalink)}.png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${esc(path.title)} — ${esc(path.tagline)}" />
    <meta name="twitter:description" content="${esc(description)}" />
    <meta name="twitter:image" content="${SITE}/assets/og/${esc(path.permalink)}.png" />

    <link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E%3Ctext y='.9em' font-size='90'%3E%F0%9F%A6%80%3C/text%3E%3C/svg%3E" />
    <link rel="stylesheet" href="assets/css/style.css" />
    <link rel="stylesheet" href="assets/css/landing.css" />
    <script>
      // Honour the theme the reader already chose in the app.
      try {
        const t = JSON.parse(localStorage.getItem("rt.theme") || '"dark"');
        if (t === "light" || t === "dark") document.documentElement.dataset.theme = t;
      } catch {}
      window.goatcounter = { no_onload: true };
    </script>
    <script data-goatcounter="https://havban.goatcounter.com/count" async src="//gc.zgo.at/count.js"></script>
  </head>
  <body class="landing">
    <header class="landing-bar">
      <a class="brand" href="index.html">
        <span class="brand-mark" aria-hidden="true">🦀</span>
        <span class="brand-text">Rust<span class="brand-dim">Tutorial</span></span>
      </a>
      <nav class="landing-nav">
        <a href="${esc(other.permalink)}.html">${esc(other.title)}</a>
        <a href="cheatsheet.html">Cheatsheet</a>
        <a href="https://github.com/havban/rust-tutorial" target="_blank" rel="noopener">GitHub</a>
      </nav>
    </header>

    <main class="landing-main">
      <p class="crumb">${esc(path.tagline)}</p>
      <h1>${esc(path.title)}</h1>
      <p class="landing-blurb">${esc(path.blurb)}</p>

      <ul class="landing-facts">
        <li><b>${lessons.length}</b> lessons</li>
        ${minutes ? `<li><b>~${minutes}</b> minutes</li>` : ""}
        <li>${esc(path.audience)}</li>
        <li>Runs real <code>rustc</code> — no install</li>
      </ul>

      <div class="landing-cta">
        <a class="btn btn-primary btn-lg" href="index.html#/${esc(lessons[0].slug)}">Start lesson 1</a>
        <a class="btn btn-lg" href="index.html#/${esc(path.permalink)}">Open in the app</a>
      </div>

${modules}

      <footer class="landing-foot">
        <p>
          Every lesson here ships with a complete, editable program. Press Run and
          it is compiled and executed by a real Rust toolchain, so the errors you
          see are the errors you would get locally.
        </p>
        <p class="landing-permalink">
          Share this page: <code>${url}</code>
        </p>
      </footer>
    </main>

    <script>
      (function count() {
        if (window.goatcounter && window.goatcounter.count) {
          window.goatcounter.count({ path: "/${esc(path.permalink)}.html", title: document.title });
        } else if ((count.n = (count.n || 0) + 1) < 20) {
          setTimeout(count, 250);
        }
      })();
    </script>
  </body>
</html>
`;
}

/* ---------------------------------------------------------------- write ---- */

for (const path of PATHS) {
  const file = join(ROOT, `${path.permalink}.html`);
  writeFileSync(file, pageHtml(path));
  const kb = (statSync(file).size / 1024).toFixed(1);
  console.log(`  ${path.permalink}.html  (${kb} KB)  -> ${SITE}/${path.permalink}.html`);
}

/* ------------------------------------------------------------ og images ---- */

if (WITH_OG) {
  const { chromium } = await import("playwright");
  const OG = join(ROOT, "assets", "og");
  mkdirSync(OG, { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });

  for (const path of PATHS) {
    const lessons = path.modules.flatMap((m) => m.lessons);
    const minutes = pathMinutes(path);
    await page.setContent(`<!doctype html><meta charset="utf-8"><style>
      *{box-sizing:border-box;margin:0}
      body{width:1200px;height:630px;display:flex;flex-direction:column;justify-content:space-between;
           padding:64px 72px;background:#15171c;color:#e4e7ec;
           font-family:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
      .top{display:flex;align-items:center;gap:14px;font-size:26px;font-weight:600;color:#99a1ae}
      .top b{color:#fff;font-weight:700}
      .tagline{color:#f97316;font-size:26px;font-weight:700;letter-spacing:.08em;text-transform:uppercase;margin-bottom:14px}
      h1{font-size:92px;line-height:1;letter-spacing:-.03em;margin-bottom:22px}
      p{font-size:30px;line-height:1.45;color:#99a1ae;max-width:22ch}
      .facts{display:flex;gap:14px;flex-wrap:wrap}
      .f{padding:10px 20px;border-radius:999px;border:1px solid #2e333d;background:#1b1e24;
         font-size:25px;color:#e4e7ec}
      .f.hot{background:rgba(249,115,22,.16);border-color:transparent;color:#f97316;font-weight:650}
      .url{font-family:ui-monospace,Menlo,monospace;font-size:23px;color:#6b7380}
      .rule{height:6px;background:#f97316;border-radius:3px;width:150px;margin-bottom:30px}
    </style>
    <div class="top"><span style="font-size:40px">🦀</span><b>Rust</b>Tutorial</div>
    <div>
      <div class="rule"></div>
      <div class="tagline">${esc(path.tagline)}</div>
      <h1>${esc(path.title)}</h1>
      <p>Learn Rust by running Rust — a real compiler, in the browser.</p>
    </div>
    <div>
      <div class="facts">
        <span class="f hot">${lessons.length} lessons</span>
        ${minutes ? `<span class="f hot">~${minutes} minutes</span>` : ""}
        <span class="f">${esc(path.audience)}</span>
      </div>
      <div class="url" style="margin-top:26px">${SITE}/${esc(path.permalink)}.html</div>
    </div>`);
    await page.waitForTimeout(120);
    const out = join(OG, `${path.permalink}.png`);
    await page.screenshot({ path: out });
    console.log(`  og/${path.permalink}.png  (${(statSync(out).size / 1024).toFixed(0)} KB)`);
  }
  await browser.close();
} else {
  console.log("  (pass --og to regenerate the social preview images)");
}
